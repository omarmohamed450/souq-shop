@Injectable({ providedIn: 'root' })
export class TranslationService {
  private readonly platformId = inject(PLATFORM_ID);
  private readonly storage = inject(BrowserStorageService);
  private readonly languageSignal = signal<Language>(this.readInitialLanguage());

  readonly language = this.languageSignal.asReadonly();
  readonly direction = computed(() => (this.language() === 'ar' ? 'rtl' : 'ltr'));

  constructor() {
    effect(() => {
      const language = this.language();

      this.storage.write(STORAGE_KEYS.language, language);

      if (isPlatformBrowser(this.platformId)) {
        document.documentElement.lang = language;
        document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
      }
    });
  }

  setLanguage(language: Language): void {
    this.languageSignal.set(language);
  }

  toggleLanguage(): void {
    this.setLanguage(this.language() === 'en' ? 'ar' : 'en');
  }

  t(key: string, params?: Record<string, string | number>): string {
    let text = DICTIONARIES[this.language()][key] ?? DICTIONARIES.en[key] ?? key;

    if (params) {
      for (const [param, value] of Object.entries(params)) {
        text = text.replaceAll(`{${param}}`, String(value));
      }
    }

    return text;
  }

  private readInitialLanguage(): Language {
    const storedLanguage = this.storage.read(STORAGE_KEYS.language);
    return storedLanguage === 'ar' ? 'ar' : 'en';
  }
}
